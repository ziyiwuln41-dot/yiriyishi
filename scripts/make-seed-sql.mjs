// Turns content/*.json into supabase/seed.sql so content can be loaded
// by pasting into the Supabase SQL Editor (no keys on your computer needed).
// Usage: node scripts/make-seed-sql.mjs
import fs from "node:fs";
const read = (d) => fs.readdirSync(d).filter((f) => f.endsWith(".json")).sort().map((f) => JSON.parse(fs.readFileSync(`${d}/${f}`, "utf8")));
const lit = (o) => `$json$${JSON.stringify(o)}$json$::jsonb`;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
let sql = "-- Generated by scripts/make-seed-sql.mjs. Safe to run again: it updates existing rows.\n\n";
for (const w of read("content/weeks")) {
  const { week_start, era, theme, ...content } = w;
  sql += `insert into weeks (week_start, era, theme, content) values (${q(week_start)}, ${q(era)}, ${q(theme)}, ${lit(content)})
on conflict (week_start) do update set era = excluded.era, theme = excluded.theme, content = excluded.content, updated_at = now();\n\n`;
}
for (const i of read("content/issues")) {
  const { date, week_start, theme, approved = false, ...content } = i;
  sql += `insert into issues (date, week_start, theme, content, approved) values (${q(date)}, ${q(week_start)}, ${q(theme)}, ${lit(content)}, ${approved})
on conflict (date) do update set week_start = excluded.week_start, theme = excluded.theme, content = excluded.content, approved = excluded.approved, updated_at = now();\n\n`;
}
fs.writeFileSync("supabase/seed.sql", sql);
console.log("Wrote supabase/seed.sql");
